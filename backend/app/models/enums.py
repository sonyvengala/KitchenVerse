"""
Enumeration definitions for roles, order states, payment statuses, and event types.
"""
import enum


class UserRole(str, enum.Enum):
    CUSTOMER = "CUSTOMER"
    KITCHEN_OWNER = "KITCHEN_OWNER"
    ADMIN = "ADMIN"


class LicenseStatus(str, enum.Enum):
    PENDING_REVIEW = "PENDING_REVIEW"
    CORRECTION_REQUIRED = "CORRECTION_REQUIRED"
    VERIFIED = "VERIFIED"
    REJECTED = "REJECTED"
    EXPIRED = "EXPIRED"


class OrderStatus(str, enum.Enum):
    ORDER_PLACED = "ORDER_PLACED"
    PAYMENT_CONFIRMED = "PAYMENT_CONFIRMED"
    KITCHEN_ACCEPTED = "KITCHEN_ACCEPTED"
    PREPARING = "PREPARING"
    READY = "READY"
    OUT_FOR_DELIVERY = "OUT_FOR_DELIVERY"
    DELIVERED = "DELIVERED"
    CANCELLED = "CANCELLED"
    REJECTED = "REJECTED"
    REFUNDED = "REFUNDED"


class PaymentStatus(str, enum.Enum):
    PENDING = "PENDING"
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    REFUNDED = "REFUNDED"


class InventoryStatus(str, enum.Enum):
    AVAILABLE = "AVAILABLE"
    LOW_STOCK = "LOW_STOCK"
    EXPIRED = "EXPIRED"


class InventoryTransactionType(str, enum.Enum):
    INWARD = "INWARD"
    OUTWARD_ORDER = "OUTWARD_ORDER"
    ADJUSTMENT = "ADJUSTMENT"
    WASTE = "WASTE"
    RETURN = "RETURN"
    TRANSFER_IN = "TRANSFER_IN"


class RealtimeEventType(str, enum.Enum):
    ORDER_CREATED = "ORDER_CREATED"
    ORDER_ACCEPTED = "ORDER_ACCEPTED"
    ORDER_REJECTED = "ORDER_REJECTED"
    ORDER_PREPARING = "ORDER_PREPARING"
    ORDER_READY = "ORDER_READY"
    ORDER_OUT_FOR_DELIVERY = "ORDER_OUT_FOR_DELIVERY"
    ORDER_DELIVERED = "ORDER_DELIVERED"
    ORDER_CANCELLED = "ORDER_CANCELLED"
    PAYMENT_CONFIRMED = "PAYMENT_CONFIRMED"
    PAYMENT_FAILED = "PAYMENT_FAILED"
    INVENTORY_UPDATED = "INVENTORY_UPDATED"
    LOW_STOCK = "LOW_STOCK"
    NOTIFICATION_CREATED = "NOTIFICATION_CREATED"
